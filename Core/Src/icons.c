void Icon_Draw(uint16_t *fb, int x, int y, Icon_t icon, uint16_t colour,
               int scale)
{
  if (icon >= ICON_COUNT)
  {
    return;
  }

  for (int row = 0; row < ICON_SIZE; row++)
  {
    const char *line = icon_art[icon][row];

    for (int col = 0; col < ICON_SIZE; col++)
    {
      if (line[col] == '#')
      {
        Gfx_Fill(fb, x + (col * scale), y + (row * scale), scale, scale,
                 colour);
      }
    }
  }
}

void Icon_Battery(uint16_t *fb, int x, int y, int percent, uint16_t colour,
                  int scale)
{
  int body_w = 21 * scale;
  int body_h = 12 * scale;
  int inner  = body_w - (4 * scale);
  int level;

  if (percent < 0)   { percent = 0;   }
  if (percent > 100) { percent = 100; }

  level = (inner * percent) / 100;

  /* Outline, contact nub, and the charge bar inside a 1-pixel gap. */
  Gfx_Fill(fb, x, y, body_w, scale, colour);
  Gfx_Fill(fb, x, y + body_h - scale, body_w, scale, colour);
  Gfx_Fill(fb, x, y, scale, body_h, colour);
  Gfx_Fill(fb, x + body_w - scale, y, scale, body_h, colour);
  Gfx_Fill(fb, x + body_w, y + (3 * scale), 2 * scale, 6 * scale, colour);

  if (level > 0)
  {
    Gfx_Fill(fb, x + (2 * scale), y + (2 * scale), level,
             body_h - (4 * scale), colour);
  }
}

void Icon_Slash(uint16_t *fb, int x, int y, int scale)
{
  for (int i = 0; i < ICON_SIZE; i++)
  {
    Gfx_Fill(fb, x + (i * scale), y + ((ICON_SIZE - 1 - i) * scale),
             2 * scale, scale, 0xF800U);
  }
}

void Icon_EffectSwatch(uint16_t *fb, int x, int y, int effect, int scale)
{
  /* Top-left, top-right, bottom-left, bottom-right quadrant colours. */
  static const uint16_t swatch[7][4] =
  {
    { GFX_RGB(230, 40, 40),  GFX_RGB(40, 200, 60),          /* std      */
      GFX_RGB(40, 90, 230),  GFX_RGB(240, 210, 40) },
    { GFX_RGB(240, 240, 240), GFX_RGB(160, 160, 160),       /* B&W      */
      GFX_RGB(90, 90, 90),   GFX_RGB(30, 30, 30) },
    { GFX_RGB(230, 200, 150), GFX_RGB(180, 140, 90),        /* sepia    */
      GFX_RGB(130, 95, 55),  GFX_RGB(80, 55, 30) },
    { GFX_RGB(25, 215, 215), GFX_RGB(215, 55, 195),         /* negative */
      GFX_RGB(215, 165, 25), GFX_RGB(15, 45, 215) },
    { GFX_RGB(250, 120, 120), GFX_RGB(220, 60, 60),         /* red      */
      GFX_RGB(160, 30, 30),  GFX_RGB(90, 15, 15) },
    { GFX_RGB(120, 240, 120), GFX_RGB(60, 200, 60),         /* green    */
      GFX_RGB(30, 140, 30),  GFX_RGB(15, 80, 15) },
    { GFX_RGB(120, 160, 250), GFX_RGB(60, 100, 230),        /* blue     */
      GFX_RGB(30, 60, 170),  GFX_RGB(15, 30, 100) },
  };
  int half = (ICON_SIZE / 2) * scale;

  if ((effect < 0) || (effect > 6))
  {
    effect = 0;
  }

  Gfx_Fill(fb, x,        y,        half, half, swatch[effect][0]);
  Gfx_Fill(fb, x + half, y,        half, half, swatch[effect][1]);
  Gfx_Fill(fb, x,        y + half, half, half, swatch[effect][2]);
  Gfx_Fill(fb, x + half, y + half, half, half, swatch[effect][3]);
  Gfx_Frame(fb, x, y, 2 * half, 2 * half, 0xFFFFU);
}
